const factory = require('../../../../src/factory')
const MOCKS = require('../../../mocks/index.mock')

beforeEach(() => {
	jest.useFakeTimers('modern').setSystemTime(new Date(2024, 4, 16, 0, 0, 0, 0))
})

describe('Given an getSendAnalyticsCollectMessagePayload call', () => {
	test('It should a response with the expected value when using CPF and channel is Whatsapp', async () => {
		const returnValue =
			factory.sqs.analyticsCollect.getSendAnalyticsCollectMessagePayload(
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_WITHCPF_WHATSAPP_PARSEDINPUT_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_PESCOD_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_ISCNPJDOCUMENT_FALSE_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_LEADID_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_LEADVINCULO_SIM_INPUT()
			)
		expect(returnValue).toEqual(
			MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_WITHCPF_WHATSAPP_VALID_RETURN()
		)
	})
	test('It should a response with the expected value when using CPF and channel is Whatsapp, with Porto relation not available', async () => {
		const returnValue =
			factory.sqs.analyticsCollect.getSendAnalyticsCollectMessagePayload(
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_WITHCNPJ_TELEFONE_PARSEDINPUT_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_PESCOD_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_ISCNPJDOCUMENT_TRUE_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_LEADID_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_LEADVINCULO_NULL_INPUT()
			)
		expect(returnValue).toEqual(
			MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_WITHCNPJ_TELEFONE_NULLPORTORELATION_VALID_RETURN()
		)
	})
	test('It should a response with the expected value when using CPF and channel is Whatsapp, without Porto relation', async () => {
		const returnValue =
			factory.sqs.analyticsCollect.getSendAnalyticsCollectMessagePayload(
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_WITHCNPJ_TELEFONE_PARSEDINPUT_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_PESCOD_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_ISCNPJDOCUMENT_TRUE_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_LEADID_INPUT(),
				MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_LEADVINCULO_NAO_INPUT()
			)
		expect(returnValue).toEqual(
			MOCKS.FACTORY_SQS_ANALYTICSCOLLECT.GETSENDANALYTICSCOLLECTMESSAGEPAYLOAD_WITHCNPJ_TELEFONE_NOPORTORELATION_VALID_RETURN()
		)
	})
})
