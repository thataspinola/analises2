const { GET_TOKEN_ERROR_DEFAULT_MESSAGE } = require('../../../src/property')
const tokenLayer = require('@porto-seguro/hub-vendas.carbon-token')
const { quotationController } = require('../../../src/controller')
const { quotationFactory, responseFactory } = require('../../../src/factory')
const { vehicleApi } = require('../../../src/api')
const { BusinessError } = require('../../../src/error')
const { logger } = require('../../../config')
const MOCK = require('../../mocks/index.mock')

jest.mock('@porto-seguro/hub-vendas.carbon-token')
jest.mock('@aws-sdk/client-sqs')
jest.mock('../../../config/logger', () => ({
	info: jest.fn(),
	error: jest.fn(),
	warn: jest.fn(),
	debug: jest.fn(),
}))
jest.mock('../../../src/service')
jest.mock('../../../src/factory')
jest.mock('../../../src/api')

afterEach(() => {
	jest.clearAllMocks()
	jest.restoreAllMocks()
	jest.resetModules()
})

describe('Test suite for quotationController.js', () => {
	test('Should invoke the token layer only once', async () => {
		const spyLayer = jest.spyOn(tokenLayer, 'getSensediaTokenHub')

		await quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)

		expect(spyLayer).toHaveBeenCalled()
		expect(spyLayer).toHaveBeenCalledTimes(1)
	})

	it('Should throw an exception when encountering an error while fetching the token', async () => {
		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockRejectedValueOnce(new Error(GET_TOKEN_ERROR_DEFAULT_MESSAGE))

		await expect(
			quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)
		).rejects.toThrow(GET_TOKEN_ERROR_DEFAULT_MESSAGE)
	})

	it('Should log an error when encountering an error while fetching the token', async () => {
		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockRejectedValueOnce(new Error())

		await expect(
			quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)
		).rejects.toThrow()
	})

	test('Should invoke the Quotation API only once with the payload generated by the Factory', async () => {
		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockResolvedValueOnce('fakeToken')
		jest
			.spyOn(quotationFactory, 'makePayload')
			.mockReturnValueOnce(
				MOCK.QUOTATION_FACTORY_PAYLOAD_RESPONSE_NEW_INSURANCE
			)

		const spyVehicleApi = jest.spyOn(vehicleApi, 'generateQuote')

		await quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)

		expect(spyVehicleApi).toHaveBeenCalled()
		expect(spyVehicleApi).toHaveBeenCalledTimes(1)
		expect(spyVehicleApi).toHaveBeenCalledWith(
			MOCK.QUOTATION_FACTORY_PAYLOAD_RESPONSE_NEW_INSURANCE,
			'fakeToken'
		)
	})

	test('Should respond with success', async () => {
		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockResolvedValueOnce('fakeToken')
		jest
			.spyOn(quotationFactory, 'makePayload')
			.mockReturnValueOnce(
				MOCK.QUOTATION_FACTORY_PAYLOAD_RESPONSE_NEW_INSURANCE
			)
		jest
			.spyOn(vehicleApi, 'generateQuote')
			.mockResolvedValueOnce(MOCK.VEHICLE_API_SUCCESS_RESPONSE)
		jest
			.spyOn(responseFactory, 'quotationSuccess')
			.mockReturnValueOnce(MOCK.RESPONSE_FACTORY_QUOTATIONS_SUCCESS)

		const response = await quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)

		expect(response).toEqual(MOCK.CONTROLLER_SUCCESS_RESPONSE)
	})

	test('Should respond with success on newJorney', async () => {
		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockResolvedValueOnce('fakeToken')
		jest
			.spyOn(quotationFactory, 'makePayload')
			.mockReturnValueOnce(
				MOCK.QUOTATION_FACTORY_PAYLOAD_RESPONSE_NEW_INSURANCE
			)
		jest
			.spyOn(vehicleApi, 'generateQuote')
			.mockResolvedValueOnce(MOCK.VEHICLE_API_SUCCESS_RESPONSE)
		jest
			.spyOn(responseFactory, 'quotationSuccess')
			.mockReturnValueOnce(MOCK.RESPONSE_FACTORY_QUOTATIONS_SUCCESS)

		const input = {
			...MOCK.VALID_INPUT_DATA_PARSED,
			auto: {
				...MOCK.VALID_INPUT_DATA_PARSED.auto,
				newJourney: 1
			}
		}
		const response = await quotationController.process(input)

		expect(response).toEqual(MOCK.CONTROLLER_SUCCESS_RESPONSE)
	})

	test('Should return error with statusCode 409 when quotation status is 4', async () => {
		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockResolvedValueOnce('fakeToken')
		jest
			.spyOn(quotationFactory, 'makePayload')
			.mockReturnValueOnce(
				MOCK.QUOTATION_FACTORY_PAYLOAD_RESPONSE_NEW_INSURANCE
			)
		const apiResponse = MOCK.VEHICLE_API_SUCCESS_RESPONSE
		apiResponse.statusCotacao = [
			{
				codigo: 4,
				descricao: 'No momento não temos ofertas disponíveis para você.',
			},
		]
		jest.spyOn(vehicleApi, 'generateQuote').mockResolvedValueOnce(apiResponse)
		jest
			.spyOn(responseFactory, 'quotationError')
			.mockReturnValueOnce(MOCK.RESPONSE_FACTORY_QUOTATIONS_BAD_REQUEST_CODE_4)

		const response = await quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)

		expect(response).toEqual(MOCK.CONTROLLER_BAD_RESPONSE_CODE_4)
	})

	test('Should return error with statusCode 409 when quotation status is 5', async () => {
		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockResolvedValueOnce('fakeToken')
		jest
			.spyOn(quotationFactory, 'makePayload')
			.mockReturnValueOnce(
				MOCK.QUOTATION_FACTORY_PAYLOAD_RESPONSE_NEW_INSURANCE
			)
		const apiResponse = MOCK.VEHICLE_API_SUCCESS_RESPONSE
		apiResponse.statusCotacao = [
			{
				codigo: 5,
				descricao:
					'Sua solicitação de Cotação está sendo analisada pela Porto Seguro. Em instantes retornaremos com as melhores ofertas para você.',
			},
		]
		jest.spyOn(vehicleApi, 'generateQuote').mockResolvedValueOnce(apiResponse)
		jest
			.spyOn(responseFactory, 'quotationError')
			.mockReturnValueOnce(MOCK.RESPONSE_FACTORY_QUOTATIONS_BAD_REQUEST_CODE_5)

		const response = await quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)

		expect(response).toEqual(MOCK.CONTROLLER_BAD_RESPONSE_CODE_5)
	})

	test('Should return statusCode 400 when code in quotation status is different from 2 and 5', async () => {
		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockResolvedValueOnce('fakeToken')
		jest
			.spyOn(quotationFactory, 'makePayload')
			.mockReturnValueOnce(
				MOCK.QUOTATION_FACTORY_PAYLOAD_RESPONSE_NEW_INSURANCE
			)
		const apiResponse = MOCK.VEHICLE_API_SUCCESS_RESPONSE
		apiResponse.statusCotacao = [
			{
				codigo: 3,
				descricao: 'Teste de mensagem genérica de erro na geração da cotação.',
			},
		]
		jest.spyOn(vehicleApi, 'generateQuote').mockResolvedValueOnce(apiResponse)
		jest
			.spyOn(responseFactory, 'quotationError')
			.mockReturnValueOnce(
				MOCK.RESPONSE_FACTORY_QUOTATIONS_BAD_REQUEST(
					apiResponse.statusCotacao[0].codigo,
					apiResponse.statusCotacao[0].descricao
				)
			)

		const response = await quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)

		expect(response).toEqual(MOCK.CONTROLLER_BAD_RESPONSE)
	})

	test('Should rethrow when encountering an error during quotation processing', async () => {
		const errorMessage = 'An error occurred during quotation processing.'
		const error = new Error(errorMessage)

		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockResolvedValueOnce('fakeToken')
		jest
			.spyOn(quotationFactory, 'makePayload')
			.mockReturnValueOnce(
				MOCK.QUOTATION_FACTORY_PAYLOAD_RESPONSE_NEW_INSURANCE
			)
		jest.spyOn(vehicleApi, 'generateQuote').mockRejectedValueOnce(error)

		await expect(
			quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)
		).rejects.toThrow(error)
	})

	test('Should rethrow when encountering a BusinessError during quotation processing', async () => {
		const errorMessage = 'An error occurred during quotation processing.'
		const error = new BusinessError(errorMessage)

		jest
			.spyOn(tokenLayer, 'getSensediaTokenHub')
			.mockResolvedValueOnce('fakeToken')
		jest
			.spyOn(quotationFactory, 'makePayload')
			.mockReturnValueOnce(
				MOCK.QUOTATION_FACTORY_PAYLOAD_RESPONSE_NEW_INSURANCE
			)
		jest.spyOn(vehicleApi, 'generateQuote').mockRejectedValueOnce(error)

		await expect(
			quotationController.process(MOCK.VALID_INPUT_DATA_PARSED)
		).rejects.toThrow(error)
	})
})
