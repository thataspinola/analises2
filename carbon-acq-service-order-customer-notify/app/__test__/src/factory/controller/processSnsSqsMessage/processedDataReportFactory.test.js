const factory = require('../../../../../src/factory')
const MOCKS = require('../../../../mocks/index.mock')

describe('getDataReport', () => {
	test('should return correct data when all values are valid', () => {
		const expectedOutput =
			MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_VALID_RETURN()
		expect(
			factory.controller.processSqsMessage.processedDataReport.getDataReport(
				MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_CUSTOMERALREADYNOTIFIED_FALSE_VALID_INPUT(),
				MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_CUSTOMERNOTIFYREQUESTSENT_TRUE_VALID_INPUT(),
				MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_UPDATECUSTOMERNOTIFYSTATUSRETURN_VALID_INPUT()
			)
		).toEqual(expectedOutput)
	})

	test('Should return N/A when a field could not get value', () => {
		const expectedOutput =
			MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_NODATA_VALID_RETURN()
		expect(
			factory.controller.processSqsMessage.processedDataReport.getDataReport(
				MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_CUSTOMERALREADYNOTIFIED_FALSE_VALID_INPUT(),
				MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_CUSTOMERNOTIFYREQUESTSENT_FALSE_VALID_INPUT()
			)
		).toEqual(expectedOutput)
	})

	test('Should return ALREADY_SENT in property customerNotifyReturnMessage when getDataReport receives input that indicates it', () => {
		const expectedOutput =
			MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_ALREADYNOTIFIED_VALID_RETURN()
		expect(
			factory.controller.processSqsMessage.processedDataReport.getDataReport(
				MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_CUSTOMERALREADYNOTIFIED_TRUE_VALID_INPUT(),
				MOCKS.FACTORY_CONTROLLER_PROCESSSNSSQSMESSAGE_PROCESSEDDATAREPORT.GETDATAREPORT_CUSTOMERNOTIFYREQUESTSENT_FALSE_VALID_INPUT()
			)
		).toEqual(expectedOutput)
	})
})
